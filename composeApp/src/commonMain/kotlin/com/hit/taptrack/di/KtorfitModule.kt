package com.hit.taptrack.di

import com.hit.taptrack.data.sources.remote.api.TapTrackApi
import com.hit.taptrack.utils.helpers.UserSettings
import de.jensklingenberg.ktorfit.Ktorfit
import de.jensklingenberg.ktorfit.converter.ResponseConverterFactory
import io.ktor.client.HttpClient
import io.ktor.client.plugins.contentnegotiation.ContentNegotiation
import io.ktor.client.plugins.defaultRequest
import io.ktor.client.plugins.logging.LogLevel
import io.ktor.client.plugins.logging.Logger
import io.ktor.client.plugins.logging.Logging
import io.ktor.http.ContentType
import io.ktor.http.contentType
import io.ktor.serialization.kotlinx.json.json
import kotlinx.serialization.json.Json
import org.koin.dsl.module
import io.ktor.client.engine.cio.CIO
import io.ktor.client.request.header
import io.ktor.http.HttpHeaders
import io.ktor.http.encodedPath
import sp.bvantur.inspektify.ktor.InspektifyKtor

/**
 * Dependency injection module for Ktorfit and network-related components.
 *
 * This module configures:
 * - A [HttpClient] with CIO engine, JSON serialization, and logging enabled.
 * - A [Ktorfit] instance pointed at the production taptrack API.
 * - API service implementations (e.g., [TapTrackApi]) generated by Ktorfit.
 */
val ktorfitModule = module {

    // Ktor HttpClient
    single {
        // 1. Ambil UserSettings dari Koin
        val userSettings = get<UserSettings>()

        HttpClient(CIO) {
            // JSON Configuration
            install(ContentNegotiation) {
                json(
                    Json {
                        ignoreUnknownKeys = true
                        isLenient = true
                        prettyPrint = true
                    }
                )
            }

            // Set Default Headers & Token Injection
            defaultRequest {
                // Set Default Content-Type to JSON
                contentType(ContentType.Application.Json)

                // 2. Ambil token saat request dibuat
                val token = userSettings.getToken()
                val currentUrlPath = url.encodedPath

                // 3. Logika Pengecualian:
                // Jika token ada DAN endpoint BUKAN login/register, sisipkan token
                if (!token.isNullOrBlank() &&
                    !currentUrlPath.contains("auth/login") &&
                    !currentUrlPath.contains("auth/register")
                ) {
                    header(HttpHeaders.Authorization, "Bearer $token")
                }
            }

            install(InspektifyKtor)

            // --- ADD THIS BLOCK ---
            install(Logging) {
                // Set the Log Level
                // ALL = Headers + Body (Like HttpLoggingInterceptor.Level.BODY)
                // INFO = Url + Method + Status
                // HEADERS = Headers only
//                level = LogLevel.ALL

                // Configure the Logger
                // Logger.SIMPLE prints to System.out (works in Logcat & Desktop Console)
                logger = object : Logger {
                    override fun log(message: String) {
                        // Custom tag makes it easy to filter in Logcat
                        println("HTTP_CLIENT: $message")
                    }
                }
            }
        }
    }

    // Ktorfit Instance
    single {
        Ktorfit.Builder()
            .httpClient(get<HttpClient>())
            .baseUrl("https://taptrack.dynodhan.xyz/api/v1/")
            .converterFactories(ResponseConverterFactory())
            .build()
    }

    // Generate the TapTrack Service
    single<TapTrackApi> {
        get<Ktorfit>().create()
    }
}